#!/usr/bin/env python3
"""Bake the bounded opening surface sample; Python standard library only.

Original procedural textures, no external imagery, model, downloads or runtime
noise. Outputs are RGB8 (opaque) PNGs. --check compares exact generated bytes
without writing; resource import sidecars are owned by Godot, not this generator.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "godot/art/surface_sample"
SIZE = 256
TERRAIN_SEED = 48011
WOOD_SEED = 48023
DECK_PLANKS = 4
DECK_PITCH_METERS = 0.37
WOOD_TILE_METERS = (DECK_PLANKS * DECK_PITCH_METERS, 3.2)


def chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)


def png(pixels: list[int]) -> bytes:
    rows = b"".join(b"\x00" + bytes(v for p in pixels[y * SIZE:(y + 1) * SIZE] for v in (p, p, p)) for y in range(SIZE))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def wrap_distance(a: float, b: float) -> float:
    return abs((a - b + 0.5) % 1.0 - 0.5)


def terrain() -> list[int]:
    rng = random.Random(TERRAIN_SEED)
    # Sparse toroidal smooth patches: no UV-dependent noise, sharp speckle or
    # fake geometry. White remains the median to limit multiplicative darkening.
    patches = [(rng.random(), rng.random(), rng.uniform(0.045, 0.11), rng.uniform(7.0, 16.0)) for _ in range(19)]
    result = []
    for y in range(SIZE):
        for x in range(SIZE):
            u, v = x / SIZE, y / SIZE
            shade = 0.0
            for px, py, radius, depth in patches:
                d2 = (wrap_distance(u, px) ** 2 + wrap_distance(v, py) ** 2) / radius ** 2
                if d2 < 1.0:
                    shade += depth * (1.0 - d2) ** 2
            result.append(255 - min(18, round(shade)))
    return result


def wood() -> list[int]:
    rng = random.Random(WOOD_SEED)
    # Long, gently bent fibres; no board boundaries or end-grain marks.
    fibres = [(rng.random(), rng.uniform(0.0025, 0.006), rng.uniform(3.0, 10.0), rng.random() * math.tau, rng.choice((1, 2, 3))) for _ in range(32)]
    result = []
    for y in range(SIZE):
        v = y / SIZE
        for x in range(SIZE):
            u = x / SIZE
            shade = 0.0
            for center, width, depth, phase, frequency in fibres:
                curve = center + 0.009 * math.sin(math.tau * v + phase) + 0.003 * math.sin(math.tau * 2 * v + phase)
                distance = wrap_distance(u, curve) / width
                if distance < 2.0:
                    variation = 0.55 + 0.45 * (0.5 + 0.5 * math.sin(math.tau * frequency * v + phase))
                    shade += depth * math.exp(-distance * distance * 1.5) * variation
            result.append(255 - min(17, round(shade)))
    return result


def deck(grain: list[int]) -> list[int]:
    result = []
    for y in range(SIZE):
        for x in range(SIZE):
            # Four 0.37 m lanes per 1.48 m tile. The shallow 2.8-pixel seam
            # footprint is colour only, not a groove, gap or new collision.
            distance = abs((x + SIZE / (DECK_PLANKS * 2)) % (SIZE / DECK_PLANKS) - SIZE / (DECK_PLANKS * 2))
            seam = 13.0 * max(0.0, 1.0 - distance / 1.4)
            result.append(max(228, grain[y * SIZE + x] - round(seam)))
    return result


def stats(pixels: list[int]) -> dict:
    ordered = sorted(pixels)
    def linear(p: int) -> float:
        v = p / 255.0
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    return {"min_byte": min(pixels), "median_byte": ordered[len(ordered) // 2], "max_byte": max(pixels),
            "mean_byte": round(sum(pixels) / len(pixels), 6),
            "mean_linear_multiplier": round(sum(linear(p) for p in pixels) / len(pixels), 6),
            "median_linear_multiplier": round(linear(ordered[len(ordered) // 2]), 6)}


def outputs() -> dict[str, bytes]:
    grain = wood()
    textures = {"terrain_detail.png": terrain(), "wood_grain.png": grain, "deck_planks.png": deck(grain)}
    files = {name: png(pixels) for name, pixels in textures.items()}
    manifest = {
        "schema": 1,
        "status": "bounded opening-surface candidate; not completed environment art",
        "provenance": {"source": "original deterministic procedural bake", "external_assets": False,
                       "runtime_generation": False, "generator": "tools/generate_surface_sample.py",
                       "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                       "dependencies": "Python standard library only", "license": "AGPL-3.0, repository LICENSE"},
        "recipe": {"size": [SIZE, SIZE], "format": "RGB8 opaque", "terrain_seed": TERRAIN_SEED,
                   "wood_seed": WOOD_SEED, "deck_source": "wood_grain.png plus shallow colour-only seams",
                   "deck_planks_per_tile": DECK_PLANKS, "deck_pitch_meters": DECK_PITCH_METERS,
                   "wood_tile_meters_xz": list(WOOD_TILE_METERS),
                   "terrain_tile_meters": {"shore": 1.8, "grass": 2.8},
                   "mapping": {
                       "terrain": "2 main-island surfaces: ordinary local-XZ UV; uv1_triplanar=false",
                       "terrain_uv": "UV=(vertex.x, vertex.z) in local meters; +X to +U, +Z to +V; emitted during original mesh construction",
                       "ship": "10 ship surfaces: unchanged local triplanar; uv1_triplanar=true",
                       "world_triplanar": False,
                   },
                   "preserved": "base albedo, roughness, culling, lighting, positions, normals, indices, triangles, bounds, collision, gameplay and save state; only two terrain UV arrays added"},
        "textures": [{"path": "godot/art/surface_sample/" + name, "bytes": len(files[name]),
                      "sha256": hashlib.sha256(files[name]).hexdigest(), "statistics": stats(pixels)}
                     for name, pixels in textures.items()],
    }
    files["asset_manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify exact generated bytes without rewriting")
    args = parser.parse_args()
    files = outputs()
    if args.check:
        bad = [name for name, data in files.items() if not (OUT / name).is_file() or (OUT / name).read_bytes() != data]
        if bad:
            parser.exit(1, "SURFACE_SAMPLE_BAKE_MISMATCH: " + ", ".join(bad) + "\n")
        print("SURFACE_SAMPLE_BAKE_OK: 3 deterministic RGB8 textures and provenance manifest")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (OUT / name).write_bytes(data)
    print("SURFACE_SAMPLE_BAKE_WRITTEN: 3 textures and provenance manifest")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
